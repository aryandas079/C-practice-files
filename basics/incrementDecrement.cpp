// this is the code to perform all the increment decrement operations 
#include<iostream> 
using namespace std; 
int main () { 
    float a = 10;  
    // now using increment and decrement notations  
    cout<<"post increment: "<<a++<<endl; //10 
    cout<<"pre increment: "<<++a<<endl; //12
    cout<<"post decrement: "<<a--<<endl; //12 
} 
